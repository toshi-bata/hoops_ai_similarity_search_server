<#
.SYNOPSIS
    Windows (PowerShell) builder for the redistributable similarity search
    server package.

.DESCRIPTION
    Creates a redistribution staging directory (redist_package\) and compresses
    it into a timestamped redist_package_<yyyyMMdd-HHmmss>.zip next to it. The
    package runs on a machine WITHOUT a HOOPS AI install. It bundles:
      - the server source (every *.py in the repository root except the
        exclusions listed below, plus routers/, vendor/, static/, ...),
      - the compiled license shim (.pyd),
      - the default embedding checkpoint(s) under models/,
      - only the site-packages actually used, from tools/trace_modules.py,
      - a .env template (tools/redist.env.example) that contains NO license key.

    The staging directory is kept after the zip is written, so its contents can
    be inspected.

.PARAMETER ModulesFile
    Module list file produced by tools/trace_modules.py --out.

.PARAMETER OutDir
    Output directory that will contain redist_package\.

.PARAMETER Ckpt
    Embedding checkpoint(s) (.ckpt) to bundle under models\. Pass a
    comma-separated array for multiple files.

.PARAMETER Sample
    Optional sample CAD files to include under samples\.

.EXAMPLE
    $env:HOOPS_AI_HOME = "C:\SDK\HOOPS_AI\V1.1"
    .\tools\build_redist_package.ps1 `
        -ModulesFile C:\temp\used_top_level_modules.txt `
        -Ckpt "$env:HOOPS_AI_HOME\packages\trained_ml_models\ts3d_2M_hoops_embeddings_SIGNAL-preview.ckpt" `
        -OutDir C:\temp\redist_out

.NOTES
    Prerequisites:
      - The compiled license shim (hoops_license_shim.*.pyd) must already be
        built (tools\build_license_shim.py) and present in the repo root.
      - $env:HOOPS_AI_HOME must point to a standard HOOPS AI installation whose
        site-packages live at $env:HOOPS_AI_HOME\.venv\Lib\site-packages.
      - PowerShell 7+ is recommended: Windows PowerShell 5.1's Compress-Archive
        cannot archive a member file larger than 2 GB, which a bundled
        checkpoint or HOOPS binary can exceed.

    Disk space: the full package can be several GB (hoops_exchange /
    hoops_converter / torch, etc.); check free space in -OutDir first.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ModulesFile,
    [Parameter(Mandatory = $true)][string]$OutDir,
    [string[]]$Ckpt = @(),
    [string[]]$Sample = @()
)

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot

if (-not (Test-Path $ModulesFile)) {
    throw "modules file not found: $ModulesFile"
}
if (-not $env:HOOPS_AI_HOME) {
    throw "Please set the HOOPS_AI_HOME environment variable"
}
$SitePackages = Join-Path $env:HOOPS_AI_HOME ".venv\Lib\site-packages"
if (-not (Test-Path $SitePackages)) {
    throw "site-packages not found: $SitePackages"
}

# The compiled license shim is what supplies the license at runtime, so the
# package must not ship a plaintext key. Require the shim and forbid a license
# line in the .env template (protects the build side against shipping a key).
$Shim = Get-ChildItem -Path $RepoRoot -Filter "hoops_license_shim*.pyd" -File -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $Shim) {
    throw "Compiled license shim (hoops_license_shim*.pyd) not found in $RepoRoot. Build it with tools\build_license_shim.py first."
}
$EnvTemplate = Join-Path $RepoRoot "tools\redist.env.example"
if (-not (Test-Path $EnvTemplate)) {
    throw ".env template not found: $EnvTemplate"
}
if (Select-String -Path $EnvTemplate -Pattern "^\s*HOOPS_AI_LICENSE\s*=" -Quiet) {
    throw "SECURITY: $EnvTemplate contains a HOOPS_AI_LICENSE line. Remove it; the key must never ship in the package."
}

$Stage = Join-Path $OutDir "redist_package"
if (Test-Path $Stage) { Remove-Item $Stage -Recurse -Force }
# Bundle the SDK site-packages under <Stage>\.venv\Lib\site-packages. main.py
# auto-detects this bundled .venv relative to its own location, so the server
# imports the bundled HOOPS AI without any system install.
$PythonPackagesDir = "$Stage\.venv\Lib\site-packages"
New-Item -ItemType Directory -Force -Path $Stage, $PythonPackagesDir, "$Stage\models", "$Stage\samples" | Out-Null

Write-Host "[1/6] Copy server source"
# The server is every *.py in the repository root, MINUS an explicit exclusion
# list. Collected, never listed: when core.py was split into per-domain modules
# this script still named five files, so 17 modules silently stopped shipping
# and the package could not start. Collecting means a module added by the next
# refactor is packaged automatically; only a file that must NOT ship needs a
# line here.
$ExcludedServerPy = @(
    # Generated by tools/build_license_shim.py as the Nuitka input. It carries
    # the license key in plain text -- the whole point of the compiled shim is
    # that this file never leaves the build machine. MUST stay excluded.
    "hoops_license_shim.py",
    # pytest-only, if one is ever added at the root.
    "conftest.py",
    # Throwaway probe recreated at the root when a latency question comes up.
    "test.py",
    # Throwaway tool: imports a hoops_ai_native_bridge index into indexes/.
    "import_bridge_index.py"
)
$ExcludedServerPyPatterns = @(
    # Proof-of-concept and measurement scripts written at the repository root
    # (all git-ignored); none of them is part of the server.
    "poc_*.py",
    "test_*.py",
    "*_test.py"
)
$ServerPy = Get-ChildItem -Path $RepoRoot -Filter "*.py" -File | Where-Object {
    $name = $_.Name
    if ($ExcludedServerPy -contains $name) { return $false }
    foreach ($pattern in $ExcludedServerPyPatterns) {
        if ($name -like $pattern) { return $false }
    }
    return $true
}
if (-not $ServerPy) {
    throw "No server modules found in $RepoRoot. Run this script from a full checkout."
}
foreach ($f in $ServerPy) { Copy-Item $f.FullName $Stage -Force }
Write-Host ("  {0} server modules" -f @($ServerPy).Count)
# Non-Python files the server itself needs. Listed rather than collected: the
# repository root also holds README/LICENSE/.gitignore and other files that are
# not part of a deployment.
$ServerFiles = @("requirements.txt", "start_server.sh")
foreach ($f in $ServerFiles) {
    $src = Join-Path $RepoRoot $f
    if (Test-Path $src) { Copy-Item $src $Stage -Force }
}
foreach ($d in @("routers", "vendor", "static")) {
    $src = Join-Path $RepoRoot $d
    if (Test-Path $src) { Copy-Item $src $Stage -Recurse -Force }
}
# The built web client lives under static/app. It is copied by the static/
# recursion above, but it is a build output that is not committed (>95%
# @ts3d-hoops code; users build it with npm). Fail hard if it is missing, the
# same way the scs_points binary below does, so we never ship a package without
# a client.
if (-not (Test-Path (Join-Path $RepoRoot "static\app\index.html"))) {
    throw "static\app\index.html is missing. Build the web client (cd web; npm ci; npm run build) before packaging."
}
# Third-party license notices. THIRD-PARTY-NOTICES.md covers the web client's
# npm dependencies; third_party_notices/ carries the acknowledgment texts for the
# third-party components embedded in the compiled HOOPS binaries (HWV browser
# viewer / wasm engine, and the libsc linked into bin/scs_points). Ship both
# alongside the built client so the redistributable carries the notices.
$Notices = Join-Path $RepoRoot "THIRD-PARTY-NOTICES.md"
if (Test-Path $Notices) { Copy-Item $Notices $Stage -Force }
$HoopsNotices = Join-Path $RepoRoot "third_party_notices"
if (Test-Path $HoopsNotices) { Copy-Item $HoopsNotices $Stage -Recurse -Force }
# The package is handed to people on its own, without this repository's README,
# so ship the sample/PoC disclaimer and the source licence alongside it.
$Disclaimer = Join-Path $RepoRoot "DISCLAIMER.txt"
if (Test-Path $Disclaimer) { Copy-Item $Disclaimer $Stage -Force }
$SourceLicense = Join-Path $RepoRoot "LICENSE"
if (Test-Path $SourceLicense) { Copy-Item $SourceLicense $Stage -Force }
# The scs_points point-cloud tool is a license-bearing binary that is not
# committed (the repository goes public). The operator builds it from
# tools/scs_points and drops the executable in bin/. Ship it so the redist
# package can serve the Shape Map point cloud; fail hard if it is missing so we
# never ship a package whose /map/scs route is dead.
# Existence is all we can check here: Windows has no execute permission bit. The
# .sh counterpart additionally requires -x, which is a genuine platform
# difference rather than a check that was forgotten on this side.
$ScsExe = if ($IsWindows -or $env:OS -eq "Windows_NT") { "scs_points.exe" } else { "scs_points" }
$ScsExePath = Join-Path $RepoRoot "bin\$ScsExe"
if (-not (Test-Path $ScsExePath)) {
    throw "bin\$ScsExe is missing. Build it from tools/scs_points (see tools/scs_points/README.md) before packaging."
}
New-Item -ItemType Directory -Force -Path "$Stage\bin" | Out-Null
Copy-Item $ScsExePath "$Stage\bin\" -Force
Copy-Item $Shim.FullName $Stage -Force
Copy-Item $EnvTemplate (Join-Path $Stage ".env") -Force

Write-Host "[2/6] Copy checkpoints and sample CAD files"
foreach ($f in $Ckpt) { if ($f) { Copy-Item $f "$Stage\models\" -Force } }
foreach ($f in $Sample) { if ($f) { Copy-Item $f "$Stage\samples\" -Force } }

Write-Host "[3/6] Copy only the required items from site-packages based on the trace results"

# Mapping for cases where the import name and distribution (wheel) name differ,
# causing the .libs directory name to differ as well (e.g. import PIL ->
# pillow.libs). If a new package causes "DLL load failed", add a mapping here.
$LibsDirAlias = @{
    "PIL"     = "pillow.libs"
    "sklearn" = "scikit_learn.libs"
    "cv2"     = "opencv_python.libs"
    "faiss"   = "faiss_cpu.libs"
}

# Tech Soft 3D packages: redistributability must be confirmed individually under
# the TPA/license agreement. Add any newly used Tech Soft 3D package here.
$Ts3dCorePackages = @{
    "hoops_ai"         = $true
    "hoops_exchange"   = $true
    "hoops_converter"  = $true
    "hoops_web_viewer" = $true
    # hoops_viewer is the Tech Soft 3D HOOPS Web Viewer package; it carries the
    # authoring assets bundled under static/javascript/communicator/ (ui-kit /
    # web-viewer-components).
    "hoops_viewer"     = $true
    # HOOPS Communicator / Web Viewer authoring libraries (libsc, hps_core) are
    # statically linked into the scs_points tool shipped under bin/. They are not
    # bundled as Python packages, but their redistributability must likewise be
    # confirmed individually under the TPA before distribution.
    "libsc"            = $true
    "hps_core"         = $true
}

$Manifest = Join-Path $Stage "THIRD_PARTY_MANIFEST.txt"
@(
    "# Bundled Python package origin / redistributability manifest"
    "# Generated at: $((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))"
    "#"
    "# [TechSoft3D] Packages provided by Tech Soft 3D. Whether they may be"
    "#   redistributed to end users depends on the specific terms of the"
    "#   TPA (partner agreement). Always confirm with your sales/licensing"
    "#   contact before distribution. Validation in this repository is only"
    "#   a technical runtime check and does not confirm license entitlement."
    "# [ThirdParty] Other third-party packages (mainly OSS). Many are usually"
    "#   low-risk for redistribution, but check individually whether each"
    "#   package requires LICENSE notices. Also refer to the dependency"
    "#   license list below:"
    "#   https://docs.techsoft3d.com/hoops/ai/resources/Acknowledgments.html"
    "#"
    "# Category,PackageName"
) | Set-Content -Path $Manifest -Encoding UTF8

Push-Location $SitePackages
try {
    foreach ($pkg in (Get-Content $ModulesFile | Where-Object { $_.Trim() -ne "" })) {
        if ($Ts3dCorePackages.ContainsKey($pkg)) {
            Add-Content -Path $Manifest -Value "TechSoft3D,$pkg"
        } else {
            Add-Content -Path $Manifest -Value "ThirdParty,$pkg"
        }

        if (Test-Path $pkg -PathType Container) {
            Copy-Item $pkg $PythonPackagesDir -Recurse -Force
        } else {
            Get-ChildItem -Path "." -Filter "$pkg.*" -File -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -notlike "*dist-info*" } |
                ForEach-Object { Copy-Item $_.FullName $PythonPackagesDir -Force }
        }

        Get-ChildItem -Path "." -Directory -Filter "$pkg-*.dist-info" -ErrorAction SilentlyContinue |
            ForEach-Object { Copy-Item $_.FullName $PythonPackagesDir -Recurse -Force }
        Get-ChildItem -Path "." -Directory -Filter "$pkg*.dist-info" -ErrorAction SilentlyContinue |
            ForEach-Object { Copy-Item $_.FullName $PythonPackagesDir -Recurse -Force }

        if (Test-Path "$pkg.libs" -PathType Container) {
            Copy-Item "$pkg.libs" $PythonPackagesDir -Recurse -Force
        }
        if ($LibsDirAlias.ContainsKey($pkg) -and (Test-Path $LibsDirAlias[$pkg] -PathType Container)) {
            Copy-Item $LibsDirAlias[$pkg] $PythonPackagesDir -Recurse -Force
        }
    }
} finally {
    Pop-Location
}
Write-Host "  -> Generated manifest: $Manifest"

Write-Host "[4/6] Final license-key safety check on the staged .env"
if (Select-String -Path (Join-Path $Stage ".env") -Pattern "^\s*HOOPS_AI_LICENSE\s*=" -Quiet) {
    throw "SECURITY: the staged .env contains a HOOPS_AI_LICENSE line. Aborting."
}

Write-Host "[5/6] Compress the staging directory"
# The staging directory is KEPT: it is what an operator inspects when something
# is missing from a package. The zip is the artifact that gets handed over.
# Timestamped so two builds on the same day never silently overwrite each other
# -- an operator can always tell which zip came from which run.
$ZipName = "redist_package_{0}.zip" -f (Get-Date).ToString("yyyyMMdd-HHmmss")
$ZipPath = Join-Path $OutDir $ZipName
try {
    # -Path $Stage (the directory itself) so the archive expands to
    # redist_package\ rather than scattering its contents.
    Compress-Archive -Path $Stage -DestinationPath $ZipPath -Force
} catch {
    throw ("Failed to compress $Stage -> $ZipPath : $($_.Exception.Message)`n" +
        "Windows PowerShell 5.1's Compress-Archive cannot handle a member file " +
        "larger than 2 GB (a bundled checkpoint or HOOPS binary can be). Run this " +
        "script under PowerShell 7+, or compress $Stage with your own archiver. " +
        "The staging directory is complete and has been kept.")
}

Write-Host "[6/6] Done"
$stageSizeGB = (Get-ChildItem $Stage -Recurse -File | Measure-Object -Property Length -Sum).Sum / 1GB
$zipSizeGB = (Get-Item $ZipPath).Length / 1GB
Write-Host ("  Staging size: {0:N2} GB" -f $stageSizeGB)
Write-Host ("  -> {0}" -f $Stage)
Write-Host ("  Package:      {0:N2} GB" -f $zipSizeGB)
Write-Host ("  -> {0}" -f $ZipPath)
Write-Host "(This is a sample package produced by a sample script. See DISCLAIMER.txt.)"
Write-Host "(Ship the .zip; the staging directory is kept so you can inspect what went in.)"
Write-Host "(See $Stage\THIRD_PARTY_MANIFEST.txt for bundled package origin and redistribution category.)"
